/** The `/hack-init` render shipped from v3.1.0 through v4.0.3. */
const HACK_INIT_V4_0_3 = [
  "---",
  "name: hack-init",
  "description: >",
  "  Stand up or adopt hack in a project (agent-assisted onboarding).",
  "  Trigger when asked to set a repo up with hack, migrate a project onto",
  "  hack, or finish/repair a partial hack setup.",
  "---",
  "",
  "# hack init (agent-assisted onboarding)",
  "",
  "The full onboarding prompt is generated by the hack CLI — do not improvise the steps.",
  "",
  "1. Fetch the canonical onboarding prompt:",
  "   - With shell access: run `hack agent onboard` (works for new and existing projects).",
  "   - Without shell access: fetch the `hack-init` MCP prompt from the hack MCP server.",
  "2. Follow the printed prompt phase by phase (inventory, setup, platform nuances, running things, verification).",
  "3. Finish only when `hack doctor` is clean and every routable service responds.",
  "",
].join("\n");

let tempDir: string | null = null;
let originalHome: string | undefined;

beforeEach(() => {
  originalHome = process.env.HOME;
});

afterEach(async () => {
  if (originalHome === undefined) {
    Reflect.deleteProperty(process.env, "HOME");
  } else {
    process.env.HOME = originalHome;
  }
  if (tempDir) {
    await rm(tempDir, { recursive: true, force: true });
    tempDir = null;
  }
});

async function setupTempDir(): Promise<string> {
  tempDir = await mkdtemp(join(tmpdir(), "hack-init-skill-"));
  return tempDir;
}

test("renderHackInitSkill is a thin pointer to the CLI prompt source", () => {
  const skill = renderHackInitSkill();
  expect(skill).toContain("name: hack-init");
  expect(skill).toContain("Stand up or adopt hack in a project");
  expect(skill).toContain("hack agent onboard");
  expect(skill).toContain("`hack-init` MCP prompt");
  // The default plugin ships no MCP, so the MCP fallback is conditional.
  expect(skill).toContain(
    "only if the `hack-mcp` plugin or another Hack MCP server is installed"
  );
  expect(skill).not.toContain("MCP prompt from the hack MCP server.");
  // Without repoRoot the MCP prompt runs no inventory, so the skill asks for it.
  expect(skill).toContain(
    "fetch the `hack-init` MCP prompt from it and pass `repoRoot`"
  );
  // Thin: the full onboarding content must NOT be duplicated into the skill.
  expect(skill).not.toContain("node_modules:/app/node_modules");
  expect(skill).not.toContain("## Phase 1");
});

test("installHackInitSkill writes project-scoped skills for both clients", async () => {
  const repoRoot = await setupTempDir();

  const claude = await installHackInitSkill({
    client: "claude",
    scope: "project",
    projectRoot: repoRoot,
  });
  const codex = await installHackInitSkill({
    client: "codex",
    scope: "project",
    projectRoot: repoRoot,
  });

  expect(claude.status).toBe("created");
  expect(codex.status).toBe("created");
  expect(claude.path).toBe(
    join(repoRoot, ".claude", "skills", "hack-init", "SKILL.md")
  );
  expect(codex.path).toBe(
    join(repoRoot, ".codex", "skills", "hack-init", "SKILL.md")
  );

  const content = await Bun.file(claude.path).text();
  expect(content).toContain("name: hack-init");
});

