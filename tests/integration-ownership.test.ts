import { afterEach, expect, test } from "bun:test";
import { mkdir, mkdtemp, readdir, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { renderCodexSkill } from "../src/agents/codex-skill.ts";
import { renderCursorRules } from "../src/agents/cursor.ts";
import { renderHackInitSkill } from "../src/agents/hack-init-skill.ts";
import { HACK_AGENT_INTEGRATION_CLI_VERSION } from "../src/agents/instruction-source.ts";
import {
  classifyIntegrationContent,
  classifyIntegrationFile,
  describePreservedReason,
  fingerprintIntegrationRender,
  type IntegrationSurface,
  installOwnedIntegrationFile,
  isKnownIntegrationRender,
  removeOwnedIntegrationFile,
} from "../src/agents/integration-ownership.ts";

/** The `/hack-init` render shipped from v3.1.0 through v4.0.3. */
const HACK_INIT_V4_0_3 = [
  "---",
  "name: hack-init",
  "description: >",
  "  Stand up or adopt hack in a project (agent-assisted onboarding).",
  "  Trigger when asked to set a repo up with hack, migrate a project onto",
  "  hack, or finish/repair a partial hack setup.",
  "---",
  "",
  "# hack init (agent-assisted onboarding)",
  "",
  "The full onboarding prompt is generated by the hack CLI — do not improvise the steps.",
  "",
  "1. Fetch the canonical onboarding prompt:",
  "   - With shell access: run `hack agent onboard` (works for new and existing projects).",
  "   - Without shell access: fetch the `hack-init` MCP prompt from the hack MCP server.",
  "2. Follow the printed prompt phase by phase (inventory, setup, platform nuances, running things, verification).",
  "3. Finish only when `hack doctor` is clean and every routable service responds.",
  "",
].join("\n");

const CURRENT_RENDERS: Readonly<Record<IntegrationSurface, () => string>> = {
  "hack-cli-skill": renderCodexSkill,
  "hack-init-skill": renderHackInitSkill,
  "cursor-rules": renderCursorRules,
};

let tempDir: string | null = null;

afterEach(async () => {
  if (tempDir) {
    await rm(tempDir, { recursive: true, force: true });
    tempDir = null;
  }
});

async function setupTempDir(): Promise<string> {
  tempDir = await mkdtemp(join(tmpdir(), "hack-integration-ownership-"));
  return tempDir;
}

test("every current render is recorded in the known render history", () => {
  for (const [surface, render] of Object.entries(CURRENT_RENDERS)) {
    const text = render();
    const fingerprint = fingerprintIntegrationRender({ text });
    expect(
      isKnownIntegrationRender({
        surface: surface as IntegrationSurface,
        text,
      }),
      `Append "${fingerprint}" to KNOWN_RENDER_FINGERPRINTS["${surface}"] in src/agents/integration-ownership.ts`
    ).toBe(true);
  }
});

test("fingerprints ignore whitespace drift and the generating CLI version", () => {
  const text = renderCodexSkill();
  expect(text).toContain(
    `generated by hack CLI v${HACK_AGENT_INTEGRATION_CLI_VERSION};`
  );
  const otherVersion = text.replace(
    `generated by hack CLI v${HACK_AGENT_INTEGRATION_CLI_VERSION};`,
    "generated by hack CLI v9.9.9-next.4;"
  );
  expect(fingerprintIntegrationRender({ text: otherVersion })).toBe(
    fingerprintIntegrationRender({ text })
  );
  expect(
    fingerprintIntegrationRender({
      text: `${text.replaceAll("\n", "  \r\n")}\n\n`,
    })
  ).toBe(fingerprintIntegrationRender({ text }));
  expect(
    fingerprintIntegrationRender({ text: text.replace("hack", "hack!") })
  ).not.toBe(fingerprintIntegrationRender({ text }));
});

test("content classification separates current, prior, customized and unknown", () => {
  const current = renderHackInitSkill();
  const classify = (content: string) =>
    classifyIntegrationContent({
      surface: "hack-init-skill",
      content,
      currentRender: current,
    });

  expect(classify(current)).toEqual({ kind: "hack-owned-current" });
  expect(classify(`${current}\n\n`)).toEqual({ kind: "hack-owned-current" });
  expect(classify(HACK_INIT_V4_0_3)).toEqual({ kind: "hack-owned-prior" });
  expect(classify(`${current}\nMy team note.\n`)).toEqual({
    kind: "customized",
    reason: "customized-content",
  });
  expect(
    classify(HACK_INIT_V4_0_3.replace("hack doctor", "hack doctor --fix"))
  ).toEqual({ kind: "customized", reason: "customized-content" });
  expect(classify("---\nname: my-init\n---\n# Mine\n")).toEqual({
    kind: "unknown",
    reason: "missing-ownership-marker",
  });
});

test("cursor rules need both integration markers to count as customized", () => {
  const current = renderCursorRules();
  const classify = (content: string) =>
    classifyIntegrationContent({
      surface: "cursor-rules",
      content,
      currentRender: current,
    });

  expect(classify(current).kind).toBe("hack-owned-current");
  expect(classify(current.replace("hack up", "hack up --verbose"))).toEqual({
    kind: "customized",
    reason: "customized-content",
  });
  expect(classify("# Our Cursor rules\n- Use pnpm.\n")).toEqual({
    kind: "unknown",
    reason: "missing-ownership-marker",
  });
  expect(classify("# BEGIN HACK INTEGRATION\nhand-written\n")).toEqual({
    kind: "unknown",
    reason: "missing-ownership-marker",
  });
});

test("file classification reports absent, non-regular and symlinked paths", async () => {
  const root = await setupTempDir();
  const currentRender = renderHackInitSkill();
  const classify = (path: string) =>
    classifyIntegrationFile({
      surface: "hack-init-skill",
      path,
      currentRender,
    });

  expect(await classify(join(root, "missing", "SKILL.md"))).toEqual({
    kind: "absent",
  });

  const dirPath = join(root, "dir", "SKILL.md");
  await mkdir(dirPath, { recursive: true });
  expect(await classify(dirPath)).toEqual({
    kind: "unknown",
    reason: "not-a-regular-file",
  });

  const dangling = join(root, "dangling.md");
  await symlink(join(root, "nowhere.md"), dangling);
  expect(await classify(dangling)).toEqual({
    kind: "unknown",
    reason: "not-a-regular-file",
  });

  const target = join(root, "target.md");
  await Bun.write(target, currentRender);
  const linked = join(root, "linked.md");
  await symlink(target, linked);
  expect(await classify(linked)).toEqual({ kind: "hack-owned-current" });
});

test("install writes absent and Hack-owned files and preserves everything else", async () => {
  const root = await setupTempDir();
  const path = join(root, "skills", "hack-init", "SKILL.md");
  const render = renderHackInitSkill();
  const install = () =>
    installOwnedIntegrationFile({ surface: "hack-init-skill", path, render });

  expect(await install()).toEqual({ status: "created" });
  expect(await install()).toEqual({ status: "noop" });

  await Bun.write(path, HACK_INIT_V4_0_3);
  expect(await install()).toEqual({ status: "updated" });
  expect(await Bun.file(path).text()).toBe(render);

  const customized = `${render}\nLocal addition.\n`;
  await Bun.write(path, customized);
  const preserved = await install();
  expect(preserved).toEqual({
    status: "preserved",
    reason: "customized-content",
    message: describePreservedReason({
      reason: "customized-content",
      action: "install",
    }),
  });
  expect(await Bun.file(path).text()).toBe(customized);
});

test("remove deletes only owned SKILL.md and never a directory with other files", async () => {
  const root = await setupTempDir();
  const skillDir = join(root, "skills", "hack-init");
  const path = join(skillDir, "SKILL.md");
  const currentRender = renderHackInitSkill();
  const remove = () =>
    removeOwnedIntegrationFile({
      surface: "hack-init-skill",
      path,
      currentRender,
      removeEmptyDirectory: true,
    });

  expect(await remove()).toEqual({ status: "missing" });

  await Bun.write(path, currentRender);
  await Bun.write(join(skillDir, "references", "notes.md"), "keep me\n");
  const removed = await remove();
  expect(removed.status).toBe("removed");
  expect(removed.status === "removed" && removed.retainedDirectory).toBe(true);
  expect(await Bun.file(path).exists()).toBe(false);
  expect(await readdir(skillDir)).toEqual(["references"]);
  expect(await Bun.file(join(skillDir, "references", "notes.md")).text()).toBe(
    "keep me\n"
  );

  await rm(join(skillDir, "references"), { recursive: true });
  await Bun.write(path, HACK_INIT_V4_0_3);
  expect(await remove()).toEqual({
    status: "removed",
    retainedDirectory: false,
  });
  expect(await Bun.file(skillDir).exists()).toBe(false);

  const customized = "---\nname: hack-init\n---\nOur own onboarding.\n";
  await Bun.write(path, customized);
  const preserved = await remove();
  expect(preserved.status).toBe("preserved");
  expect(await Bun.file(path).text()).toBe(customized);
});

test("remove unlinks a symlinked skill directory without touching its target", async () => {
  const root = await setupTempDir();
  const shared = join(root, "shared", "hack-init");
  await Bun.write(join(shared, "SKILL.md"), renderHackInitSkill());
  const linkedDir = join(root, "client", "hack-init");
  await mkdir(join(root, "client"), { recursive: true });
  await symlink(shared, linkedDir);

  const removed = await removeOwnedIntegrationFile({
    surface: "hack-init-skill",
    path: join(linkedDir, "SKILL.md"),
    currentRender: renderHackInitSkill(),
    removeEmptyDirectory: true,
  });
  expect(removed).toEqual({ status: "removed", retainedDirectory: false });
  expect(await readdir(join(root, "client"))).toEqual([]);
  expect(await Bun.file(join(shared, "SKILL.md")).text()).toBe(
    renderHackInitSkill()
  );
});

test("preserved reasons are fixed operator text without file content", () => {
  for (const reason of [
    "customized-content",
    "missing-ownership-marker",
    "not-a-regular-file",
    "unreadable",
  ] as const) {
    for (const action of ["install", "remove"] as const) {
      const message = describePreservedReason({ reason, action });
      expect(message).toStartWith("Hack left this path unchanged because");
      expect(message).not.toContain("SKILL.md");
    }
  }
});
