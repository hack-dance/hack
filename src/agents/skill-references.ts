const REFERENCE_FILE_PATTERN = /^[a-z0-9][a-z0-9-]*\.md$/;

/** References that belong to one skill. */
export function referencesForSkill(
  skill: PluginSkillName
): readonly SkillReference[] {
  return SKILL_REFERENCES.filter((reference) => reference.skill === skill);
}

/** Path of a reference relative to the plugin root. */
export function skillReferencePath(reference: SkillReference): string {
  assertReferenceFile(reference.file);
  return `skills/${reference.skill}/references/${reference.file}`;
}

/** First 12 hex characters of the SHA-256 of a reference body. */
export function skillReferenceRevision(body: string): string {
  return createHash("sha256").update(body).digest("hex").slice(0, 12);
}

/**
 * Render the packaged reference file: the canonical body plus a content
 * revision that a reader (or test) can recompute from the body above it.
 */
export function renderSkillReference(reference: SkillReference): string {
  assertReferenceFile(reference.file);
  const body = reference.render();
  return `${body.trimEnd()}\n\n---\n\nContent revision: \`${skillReferenceRevision(body)}\`. Generated by Hack; edit the canonical source and regenerate the plugin.\n`;
}

/**
 * Append a References section that links each of the skill's packaged
 * references. Skills without references are returned unchanged, so the
 * standalone installs (which ship no references) never gain a dangling link.
 */
export function withSkillReferenceLinks(opts: {
  readonly skill: PluginSkillName;
  readonly content: string;
}): string {
  const references = referencesForSkill(opts.skill);
  if (references.length === 0) {
    return opts.content;
  }
  const links = references.map((reference) => {
    assertReferenceFile(reference.file);
    return `- [${reference.title}](references/${reference.file}): ${reference.summary}`;
  });
  return `${opts.content.trimEnd()}\n\n## References\n\n${links.join("\n")}\n`;
}

function assertReferenceFile(file: string): void {
  if (!REFERENCE_FILE_PATTERN.test(file)) {
    throw new Error("Invalid skill reference file name");
  }
}
