test("project and user hack-init duplicates are classified independently", async () => {
  const root = await setupTempDir();
  const home = join(root, "home");
  const repoRoot = join(root, "repo");
  await mkdir(home, { recursive: true });
  await mkdir(repoRoot, { recursive: true });
  process.env.HOME = home;

  const project = {
    client: "claude",
    scope: "project",
    projectRoot: repoRoot,
  } as const;
  const user = { client: "claude", scope: "user" } as const;
  expect((await installHackInitSkill(project)).status).toBe("created");
  const userInstall = await installHackInitSkill(user);
  expect(userInstall.status).toBe("created");

  const customized = `${renderHackInitSkill()}\nPersonal reminder.\n`;
  await Bun.write(userInstall.path, customized);

  expect((await removeHackInitSkill(project)).status).toBe("removed");
  expect(await Bun.file(userInstall.path).text()).toBe(customized);

  expect((await installHackInitSkill(user)).status).toBe("preserved");
  expect((await removeHackInitSkill(user)).status).toBe("preserved");
  expect(await Bun.file(userInstall.path).text()).toBe(customized);

  expect((await installHackInitSkill(project)).status).toBe("created");
});

test("removeClaudeHooks keeps other commands that share a hook group", async () => {
  const repoRoot = await setupTempDir();
  const settingsPath = join(repoRoot, ".claude", "settings.local.json");
  await Bun.write(
    settingsPath,
    `${JSON.stringify(
      {
        model: "opus",
        hooks: {
          SessionStart: [
            {
              matcher: "",
              hooks: [
                { type: "command", command: "hack agent prime" },
                { type: "command", command: "./scripts/team-start.sh" },
              ],
            },
          ],
          PreCompact: [
            {
              matcher: "",
              hooks: [{ type: "command", command: "hack agent prime" }],
            },
          ],
        },
      },
      null,
      2
    )}\n`
  );

  const removed = await removeClaudeHooks({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(removed.status).toBe("removed");
  const settings = JSON.parse(await Bun.file(settingsPath).text()) as {
    readonly model: string;
    readonly hooks: Record<string, unknown>;
  };
  expect(settings.model).toBe("opus");
  expect(settings.hooks.SessionStart).toEqual([
    {
      matcher: "",
      hooks: [{ type: "command", command: "./scripts/team-start.sh" }],
    },
  ]);
  expect(settings.hooks.PreCompact).toEqual([]);
});

