import { createHash } from "node:crypto";
import { YAML } from "bun";

const EMPTY_MAPPING_SPACE = /: \n/g;

/**
 * Literal projection that Hack versions before the reference writer kept at
 * `.hack/.internal/compose.env.override.yml`. No writer emits it now; strict
 * adoption qualification still recognizes such files, and
 * {@link renderComposeEnvReferenceOverride} is the form written today.
 * Input and output contain private runtime values: never log or serialize them
 * into reports or public receipts, and never write them to disk. Target order and key order are preserved so
 * existing generated bytes can be checked exactly. This performs no I/O.
 */
export function renderManagedComposeEnvOverride(opts: {
  readonly targetServices: readonly string[];
  readonly globalEnv: Readonly<Record<string, string>>;
  readonly serviceEnv: Readonly<
    Record<string, Readonly<Record<string, string>>>
  >;
}): string | null {
  const services: Record<
    string,
    { readonly environment: Readonly<Record<string, string>> }
  > = {};
  for (const service of opts.targetServices) {
    const env = opts.serviceEnv[service] ?? opts.globalEnv;
    if (Object.keys(env).length > 0) {
      services[service] = { environment: env };
    }
  }
  if (Object.keys(services).length === 0) {
    return null;
  }
  const text = YAML.stringify({ services }, null, 2).replaceAll(
    EMPTY_MAPPING_SPACE,
    ":\n"
  );
  return text.endsWith("\n") ? text : `${text}\n`;
}

/** Prefix of the interpolation variables that carry managed env values to Compose. */
export const COMPOSE_ENV_REFERENCE_PREFIX = "HACK_ENV_";

const ENV_NAME_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/;
const COMPOSE_REFERENCE_PATTERN = /^\$\{[A-Za-z_][A-Za-z0-9_]*\}$/;

/**
 * Deterministic Compose interpolation variable for one service's key.
 *
 * The name depends only on the service and key, never on the value, so the
 * rendered override is value-free and stays byte-stable while values change.
 * The digest keeps names distinct across services that share a key and keeps
 * arbitrary service names inside the variable grammar.
 */
export function composeEnvReferenceName(opts: {
  readonly service: string;
  readonly key: string;
}): string {
  const digest = createHash("sha256")
    .update(`${opts.service}\0${opts.key}`)
    .digest("hex")
    .slice(0, 12)
    .toUpperCase();
  return ENV_NAME_PATTERN.test(opts.key)
    ? `${COMPOSE_ENV_REFERENCE_PREFIX}${digest}_${opts.key}`
    : `${COMPOSE_ENV_REFERENCE_PREFIX}${digest}`;
}

/**
 * Deterministic Compose interpolation variable shared by every service whose
 * value for `key` comes from the global scope.
 *
 * Like {@link composeEnvReferenceName}, the name depends only on the key. Its
 * digest input `\0global\0<key>` differs from every per-service input
 * `<service>\0<key>`, including a service named `global`: they could only
 * meet for an empty service name and a key holding a NUL, which neither
 * Compose nor an environment allows.
 */
export function composeEnvGlobalReferenceName(opts: {
  readonly key: string;
}): string {
  const digest = createHash("sha256")
    .update(`\0global\0${opts.key}`)
    .digest("hex")
    .slice(0, 12)
    .toUpperCase();
  return ENV_NAME_PATTERN.test(opts.key)
    ? `${COMPOSE_ENV_REFERENCE_PREFIX}${digest}_${opts.key}`
    : `${COMPOSE_ENV_REFERENCE_PREFIX}${digest}`;
}

const COMPOSE_ENV_REFERENCE_NAME = /^HACK_ENV_[0-9A-F]{12}(?:_|$)/;

/**
 * True for a name {@link composeEnvReferenceName} or
 * {@link composeEnvGlobalReferenceName} can produce.
 */
export function isComposeEnvReferenceName(name: string): boolean {
  return COMPOSE_ENV_REFERENCE_NAME.test(name);
}

/**
 * Copy of `env` without the `HACK_ENV_*` reference values. Only a
 * `docker compose` invocation that reads the generated override needs them;
 * every other child (for example `docker inspect` or `docker events`) gets
 * this copy, so the private per-service values reach no process that cannot
 * use them.
 */
export function withoutComposeEnvReferences(
  env: Readonly<Record<string, string>> | undefined
): Record<string, string> | undefined {
  if (!env) {
    return env;
  }
  const kept: Record<string, string> = {};
  for (const [key, value] of Object.entries(env)) {
    if (!isComposeEnvReferenceName(key)) {
      kept[key] = value;
    }
  }
  return kept;
}

/**
 * Value-free managed override plus the private values it references.
 *
 * `text` is safe to keep on disk: every environment value is a single
 * `${NAME}` reference. `env` maps each NAME to its private value and must be
 * delivered only through the Compose process environment; never persist, log
 * or serialize it. Compose substitutes each reference once, so a value that
 * contains `$` reaches the container literally.
 */
export type ComposeEnvReferenceOverride = {
  readonly text: string;
  readonly env: Readonly<Record<string, string>>;
};

/**
 * Winning scope of each service's keys, as in the resolved env config's
 * `effectiveMetadata`. Names and scope names only; never a value.
 */
export type ComposeEnvEffectiveScopes = Readonly<
  Record<string, Readonly<Record<string, { readonly scope: string }>>>
>;

/**
 * Same service/key selection and order as {@link renderManagedComposeEnvOverride},
 * with every value replaced by a Compose interpolation reference. Pure; no I/O.
 *
 * With `effectiveScopes`, a key whose winning scope for a service is
 * `global` uses one {@link composeEnvGlobalReferenceName} reference shared by
 * every such service, so the Compose process environment grows with distinct
 * values instead of services times keys (HACK-1317). A service missing from
 * `serviceEnv` takes the global values and shares the same references. A key a
 * service scope sets keeps its own {@link composeEnvReferenceName} reference.
 * The choice follows the scope metadata, not the values, so the text still
 * does not depend on any value. As a guard, a key the metadata calls global
 * whose value differs from the global value keeps its own reference, so a
 * container always gets its own resolved value.
 *
 * Without `effectiveScopes`, every service gets its own reference for every
 * key: the form Hack wrote before shared references, which adoption still
 * recognizes in a saved generation.
 */
export function renderComposeEnvReferenceOverride(opts: {
  readonly targetServices: readonly string[];
  readonly globalEnv: Readonly<Record<string, string>>;
  readonly serviceEnv: Readonly<
    Record<string, Readonly<Record<string, string>>>
  >;
  readonly effectiveScopes?: ComposeEnvEffectiveScopes;
}): ComposeEnvReferenceOverride | null {
  const services: Record<
    string,
    { readonly environment: Readonly<Record<string, string>> }
  > = {};
  const env: Record<string, string> = {};
  const sharing = opts.effectiveScopes !== undefined;
  for (const service of opts.targetServices) {
    const scoped = opts.serviceEnv[service];
    const values = scoped ?? opts.globalEnv;
    const scopes =
      scoped !== undefined &&
      opts.effectiveScopes !== undefined &&
      Object.hasOwn(opts.effectiveScopes, service)
        ? opts.effectiveScopes[service]
        : undefined;
    const environment: Record<string, string> = {};
    for (const [key, value] of Object.entries(values)) {
      const fromGlobal =
        sharing &&
        Object.hasOwn(opts.globalEnv, key) &&
        opts.globalEnv[key] === value &&
        (scoped === undefined ||
          (scopes !== undefined &&
            Object.hasOwn(scopes, key) &&
            scopes[key]?.scope === "global"));
      const name = fromGlobal
        ? composeEnvGlobalReferenceName({ key })
        : composeEnvReferenceName({ service, key });
      environment[key] = `\${${name}}`;
      env[name] = value;
    }
    if (Object.keys(environment).length > 0) {
      services[service] = { environment };
    }
  }
  if (Object.keys(services).length === 0) {
    return null;
  }
  const text = YAML.stringify({ services }, null, 2).replaceAll(
    EMPTY_MAPPING_SPACE,
    ":\n"
  );
  return { text: text.endsWith("\n") ? text : `${text}\n`, env };
}

/**
 * What a generated Compose env override holds at rest. Counts only; never a
 * key or value.
 * - `references`: every environment value is a bare key or one `${NAME}`
 *   reference, so the file holds no env value.
 * - `plaintext`: at least one environment value is a literal.
 * - `unverifiable`: the text is not a Compose services document Hack can
 *   check, so it may hold literal values.
 */
export type ComposeEnvOverrideContent =
  | { readonly kind: "references" }
  | {
      readonly kind: "plaintext";
      readonly services: number;
      readonly values: number;
    }
  | { readonly kind: "unverifiable" };

function countLiteralEnvironmentValues(environment: unknown): number | null {
  if (environment === undefined || environment === null) {
    return 0;
  }
  if (Array.isArray(environment)) {
    let literals = 0;
    for (const item of environment) {
      if (typeof item !== "string") {
        literals += 1;
        continue;
      }
      const separator = item.indexOf("=");
      if (
        separator >= 0 &&
        !COMPOSE_REFERENCE_PATTERN.test(item.slice(separator + 1))
      ) {
        literals += 1;
      }
    }
    return literals;
  }
  if (typeof environment !== "object") {
    return null;
  }
  let literals = 0;
  for (const value of Object.values(environment)) {
    if (value === null) {
      continue;
    }
    if (typeof value !== "string" || !COMPOSE_REFERENCE_PATTERN.test(value)) {
      literals += 1;
    }
  }
  return literals;
}

/**
 * Classifies generated override text without returning any of it. Pure.
 */
export function classifyComposeEnvOverrideText(
  text: string
): ComposeEnvOverrideContent {
  let parsed: unknown;
  try {
    parsed = YAML.parse(text);
  } catch {
    return { kind: "unverifiable" };
  }
  if (parsed === null || parsed === undefined) {
    return { kind: "references" };
  }
  if (typeof parsed !== "object" || Array.isArray(parsed)) {
    return { kind: "unverifiable" };
  }
  const services = (parsed as Record<string, unknown>).services;
  if (services === undefined || services === null) {
    return { kind: "references" };
  }
  if (typeof services !== "object" || Array.isArray(services)) {
    return { kind: "unverifiable" };
  }
  let plaintextServices = 0;
  let values = 0;
  for (const service of Object.values(services)) {
    if (service === null) {
      continue;
    }
    if (typeof service !== "object" || Array.isArray(service)) {
      return { kind: "unverifiable" };
    }
    const literals = countLiteralEnvironmentValues(
      (service as Record<string, unknown>).environment
    );
    if (literals === null) {
      return { kind: "unverifiable" };
    }
    if (literals > 0) {
      plaintextServices += 1;
      values += literals;
    }
  }
  return values > 0
    ? { kind: "plaintext", services: plaintextServices, values }
    : { kind: "references" };
}
