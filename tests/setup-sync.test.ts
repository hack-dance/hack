/**
 * `hack setup sync` engine tests (HACK-1132). Every call passes a temp
 * project root or temp home explicitly. `HOME` is pointed at an empty decoy
 * directory for each test and asserted untouched afterwards, so a fallback
 * to the process `HOME` fails the test instead of writing real client config.
 */

/** The `/hack-init` render shipped from v3.1.0 through v4.0.3. */
const HACK_INIT_V4_0_3 = [
  "---",
  "name: hack-init",
  "description: >",
  "  Stand up or adopt hack in a project (agent-assisted onboarding).",
  "  Trigger when asked to set a repo up with hack, migrate a project onto",
  "  hack, or finish/repair a partial hack setup.",
  "---",
  "",
  "# hack init (agent-assisted onboarding)",
  "",
  "The full onboarding prompt is generated by the hack CLI — do not improvise the steps.",
  "",
  "1. Fetch the canonical onboarding prompt:",
  "   - With shell access: run `hack agent onboard` (works for new and existing projects).",
  "   - Without shell access: fetch the `hack-init` MCP prompt from the hack MCP server.",
  "2. Follow the printed prompt phase by phase (inventory, setup, platform nuances, running things, verification).",
  "3. Finish only when `hack doctor` is clean and every routable service responds.",
  "",
].join("\n");

let tempRoot: string | null = null;
let decoyHome = "";
const originalHome = process.env.HOME;

beforeEach(async () => {
  tempRoot = await mkdtemp(join(tmpdir(), "hack-setup-sync-"));
  decoyHome = join(tempRoot, "decoy-home");
  await mkdir(decoyHome, { recursive: true });
  process.env.HOME = decoyHome;
});

afterEach(async () => {
  try {
    expect(
      await listFiles(decoyHome),
      "setup sync must not resolve paths from the process HOME"
    ).toEqual([]);
  } finally {
    if (originalHome === undefined) {
      Reflect.deleteProperty(process.env, "HOME");
    } else {
      process.env.HOME = originalHome;
    }
    if (tempRoot) {
      await rm(tempRoot, { recursive: true, force: true });
      tempRoot = null;
    }
  }
});

async function makeRoot(name: string): Promise<string> {
  if (!tempRoot) {
    throw new Error("temp root not initialized");
  }
  const root = join(tempRoot, name);
  await mkdir(root, { recursive: true });
  return root;
}

async function writeFile(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await Bun.write(path, content);
}

async function listFiles(root: string): Promise<string[]> {
  const entries = await readdir(root, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name).slice(root.length + 1))
    .sort();
}

async function snapshot(root: string): Promise<Map<string, string>> {
  const files = await listFiles(root);
  const contents = new Map<string, string>();
  for (const file of files) {
    contents.set(file, await Bun.file(join(root, file)).text());
  }
  return contents;
}

async function run(opts: {
  readonly action: SetupSyncAction;
  readonly scope: SetupSyncScope;
  readonly root: string;
  readonly installMissing?: boolean;
}): Promise<SetupSyncTargetResult[]> {
  return await runSetupSyncScope({
    action: opts.action,
    scope: opts.scope,
    root: opts.root,
    installMissing: opts.installMissing ?? false,
  });
}

function byTarget(
  results: readonly SetupSyncTargetResult[],
  target: SetupSyncTarget
): SetupSyncTargetResult {
  const found = results.find((result) => result.target === target);
  if (!found) {
    throw new Error(`no result for ${target}`);
  }
  return found;
}

function statuses(
  results: readonly SetupSyncTargetResult[]
): Record<string, string> {
  return Object.fromEntries(
    results.map((result) => [result.target, result.status])
  );
}

