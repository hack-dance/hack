/** Plugin skills that can carry packaged references. */
export type PluginSkillName =
  | "hack-cli"
  | "hack-branches"
  | "hack-env"
  | "hack-diagnose"
  | "hack-feedback"
  | "hack-init"
  | "hack-install"
  | "hack-remote";

/**
 * A markdown reference shipped inside the plugin package at
 * `skills/<skill>/references/<file>`.
 *
 * References are offline-first: they resolve inside the installed package,
 * link only to files inside it, and keep external URLs under a
 * "Further reading" heading. Each one is linked from its skill's SKILL.md.
 */
export type SkillReference = {
  readonly skill: PluginSkillName;
  /** Lowercase kebab-case markdown file name, e.g. `patterns.md`. */
  readonly file: string;
  /** Link text used in the skill's References section. */
  readonly title: string;
  /** One-line description shown next to the link. */
  readonly summary: string;
  /** Canonical body; the packaged file adds a revision footer. */
  readonly render: () => string;
};

/** Every packaged skill reference, in generation order. */
