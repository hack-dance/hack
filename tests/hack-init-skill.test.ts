test("a customized hack-init SKILL.md survives remove and install byte-identical", async () => {
  const repoRoot = await setupTempDir();
  const skillPath = join(
    repoRoot,
    ".claude",
    "skills",
    "hack-init",
    "SKILL.md"
  );
  const customized = `${renderHackInitSkill()}\n## Team notes\n- Ask before running hack down.\n`;
  await Bun.write(skillPath, customized);
  const opts = {
    client: "claude",
    scope: "project",
    projectRoot: repoRoot,
  } as const;

  const removed = await removeHackInitSkill(opts);
  expect(removed.status).toBe("preserved");
  expect(removed.reason).toBe("customized-content");
  expect(removed.message).toContain("unchanged");
  expect(await Bun.file(skillPath).text()).toBe(customized);

  const installed = await installHackInitSkill(opts);
  expect(installed.status).toBe("preserved");
  expect(installed.reason).toBe("customized-content");
  expect(await Bun.file(skillPath).text()).toBe(customized);

  const viaClaude = await installClaudeHooks({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(viaClaude.status).toBe("preserved");
  expect(viaClaude.path).toBe(skillPath);
  expect(await Bun.file(skillPath).text()).toBe(customized);
});

