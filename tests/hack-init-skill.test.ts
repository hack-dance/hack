test("installCodexSkill also installs the hack-init skill and detects its drift", async () => {
  const repoRoot = await setupTempDir();

  const installed = await installCodexSkill({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(installed.status).toBe("created");

  const initSkillPath = join(
    repoRoot,
    ".codex",
    "skills",
    "hack-init",
    "SKILL.md"
  );
  const content = await Bun.file(initSkillPath).text();
  expect(content).toContain("name: hack-init");

  const fresh = await checkCodexSkill({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(fresh.status).toBe("noop");

  await Bun.write(initSkillPath, content.replace("hack agent onboard", "nope"));
  const stale = await checkCodexSkill({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(stale.status).toBe("stale");

  // The edited hack-init skill is no longer Hack-owned: remove keeps it.
  const edited = await Bun.file(initSkillPath).text();
  const kept = await removeCodexSkill({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(kept.status).toBe("preserved");
  expect(kept.path).toBe(initSkillPath);
  expect(kept.reason).toBe("customized-content");
  expect(await Bun.file(initSkillPath).text()).toBe(edited);
  expect(
    await Bun.file(
      join(repoRoot, ".codex", "skills", "hack-cli", "SKILL.md")
    ).exists()
  ).toBe(false);

  await Bun.write(initSkillPath, content);
  const removed = await removeCodexSkill({
    scope: "project",
    projectRoot: repoRoot,
  });
  expect(removed.status).toBe("removed");
  expect(await Bun.file(initSkillPath).exists()).toBe(false);
  expect(await readdir(join(repoRoot, ".codex", "skills"))).toEqual([]);
});

