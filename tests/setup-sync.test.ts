test("JSON data lists every target with its status and reason", async () => {
  const project = await makeRoot("project");
  await writeFile(join(project, ".cursor/rules/hack.mdc"), "team rules\n");
  const results = await run({
    action: "sync",
    scope: "project",
    root: project,
  });
  const data = buildSetupSyncJsonData({
    action: "sync",
    installMissing: false,
    results,
  });
  expect(data.action).toBe("sync");
  expect(data.dryRun).toBe(false);
  expect(data.counts).toEqual({
    preserved: 1,
    missing: PROJECT_TARGETS.length - 1,
  });
  expect(data.targets[0]).toEqual({
    scope: "project",
    target: "cursor-rules",
    path: join(project, ".cursor/rules/hack.mdc"),
    status: "preserved",
    reason: "missing-ownership-marker",
    message: expect.stringContaining("no Hack ownership marker"),
  });
  const serialized = JSON.stringify(data);
  expect(serialized).not.toContain("team rules");
});
